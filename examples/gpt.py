"""Weeks 9-10: train a GPT on Tiny Shakespeare with our compiler, then sample from it.

  python examples/gpt.py                    # small model, a few minutes on a laptop CPU
  python examples/gpt.py --steps 2000 --layers 4 --dim 128

Everything -- embeddings, causal attention, LayerNorm, GELU, AdamW, the backward pass --
is graph building on the Tensor API. Every kernel it runs was generated by uopc.
"""
import argparse, math, sys, time
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import numpy as np
from datasets import shakespeare
from uopc.tensor import Tensor
from uopc.nn import Linear, LayerNorm, Embedding, AdamW, parameters


class Attention:
  def __init__(self, dim: int, heads: int, ctx: int):
    self.qkv, self.proj, self.heads = Linear(dim, 3 * dim), Linear(dim, dim), heads
    mask = np.triu(np.full((ctx, ctx), -1e9, np.float32), 1)       # -inf above the diagonal: no peeking
    self.mask = Tensor(mask)

  def __call__(self, x: Tensor) -> Tensor:
    B, T, C = x.shape
    H, D = self.heads, C // self.heads
    qkv = self.qkv(x).reshape(B, T, 3, H, D)
    q, k, v = (qkv[:, :, i].permute(0, 2, 1, 3) for i in range(3))   # (B, H, T, D)
    att = (q @ k.transpose()) * (1 / math.sqrt(D)) + self.mask[:T, :T].reshape(1, 1, T, T)
    y = att.softmax(-1) @ v                                            # (B, H, T, D)
    return self.proj(y.permute(0, 2, 1, 3).reshape(B, T, C))


class Block:
  def __init__(self, dim, heads, ctx):
    self.ln1, self.attn, self.ln2 = LayerNorm(dim), Attention(dim, heads, ctx), LayerNorm(dim)
    self.fc, self.out = Linear(dim, 4 * dim), Linear(4 * dim, dim)
  def __call__(self, x: Tensor) -> Tensor:
    x = x + self.attn(self.ln1(x))
    return x + self.out(self.fc(self.ln2(x)).gelu())


class GPT:
  def __init__(self, vocab, ctx, dim, heads, layers):
    self.tok, self.pos = Embedding(vocab, dim), Tensor.randn(ctx, dim) * 0.02
    self.pos = self.pos.realize(); self.pos.requires_grad = True
    self.blocks = [Block(dim, heads, ctx) for _ in range(layers)]
    self.ln, self.head = LayerNorm(dim), Linear(dim, vocab)
  def __call__(self, idx: Tensor) -> Tensor:
    B, T = idx.shape
    x = self.tok(idx) + self.pos[:T].reshape(1, T, -1)
    for b in self.blocks: x = b(x)
    return self.head(self.ln(x))


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--steps", type=int, default=600)
  ap.add_argument("--batch", type=int, default=16)
  ap.add_argument("--ctx", type=int, default=64)
  ap.add_argument("--dim", type=int, default=64)
  ap.add_argument("--heads", type=int, default=4)
  ap.add_argument("--layers", type=int, default=2)
  ap.add_argument("--lr", type=float, default=3e-3)
  a = ap.parse_args()

  text = shakespeare()
  chars = sorted(set(text))
  stoi = {c: i for i, c in enumerate(chars)}
  data = np.array([stoi[c] for c in text], np.int32)
  split = int(0.9 * len(data))
  train, val = data[:split], data[split:]
  rng = np.random.default_rng(0)
  def batch(src):
    ix = rng.integers(0, len(src) - a.ctx - 1, a.batch)
    return Tensor(np.stack([src[i:i + a.ctx] for i in ix])), Tensor(np.stack([src[i + 1:i + a.ctx + 1] for i in ix]))

  Tensor.manual_seed(0)
  model = GPT(len(chars), a.ctx, a.dim, a.heads, a.layers)
  params = parameters(model)
  print(f"{sum(p.numel() for p in params) / 1e3:.1f}k parameters, vocab {len(chars)}")
  opt = AdamW(params, lr=a.lr, wd=0.01)
  t0 = time.perf_counter()
  for step in range(a.steps):
    x, y = batch(train)
    loss = model(x).reshape(-1, len(chars)).cross_entropy(y.reshape(-1))
    opt.zero_grad()
    loss.backward(opt.params)
    opt.step(loss)
    if step % 50 == 0 or step == a.steps - 1:
      vx, vy = batch(val)
      vloss = model(vx).reshape(-1, len(chars)).cross_entropy(vy.reshape(-1)).item()
      print(f"step {step:5d}  train {loss.item():.3f}  val {vloss:.3f}  {(time.perf_counter() - t0) / (step + 1) * 1e3:6.0f} ms/step")

  # sample: feed the last ctx characters, draw the next one from the softmax
  idx = [stoi["\n"]]
  for _ in range(300):
    ctx = idx[-a.ctx:]
    ctx = ctx + [0] * (a.ctx - len(ctx))                           # fixed shape -> one compiled graph
    logits = model(Tensor(np.array([ctx], np.int32))).numpy()[0, min(len(idx), a.ctx) - 1]
    p = np.exp(logits - logits.max()); p /= p.sum()
    idx.append(int(rng.choice(len(chars), p=p)))
  print("".join(chars[i] for i in idx))


if __name__ == "__main__": main()
